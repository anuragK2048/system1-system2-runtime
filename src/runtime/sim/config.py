# ==============================================================================
# DRONE PHYSICAL PARAMETERS & CONTROL ALLOCATION
# ==============================================================================
@dataclass
class DroneConfig:
    """Physical specifications and rotor configuration of the Skydio X2.
    
    The Skydio X2 is an X-configuration quadrotor. It has 4 motors:
      - Motor 1 (thrust1): Rear-Left   (spin CW)
      - Motor 2 (thrust2): Rear-Right  (spin CCW)
      - Motor 3 (thrust3): Front-Right (spin CW)
      - Motor 4 (thrust4): Front-Left  (spin CCW)
    """
    # Mass of drone is ~1.325 kg, so total weight under gravity (W = mg) is ~13 Newtons.
    # At steady hover, each motor must produce 1/4 of total weight (~3.25 N).
    hover_thrust_per_motor: float = 3.2495625  # Newtons per rotor
    total_hover_weight: float = 4.0 * 3.2495625  # ~12.998 Newtons
    
    # Target hover altitude in meters (global Z axis)
    target_z: float = 1.0
    
    # Initial spawn position [x, y, z] in meters
    spawn_pos: np.ndarray = field(default_factory=lambda: np.array([0.0, 0.0, 0.8]))
    
    # Motor physical thrust limits [min, max] in Newtons per motor
    min_thrust: float = 0.0
    max_thrust: float = 13.0
    
    # CONTROL ALLOCATION MATRIX INVERSE (B_INV):
    # Converts 4 virtual control demands [F_z, tau_x, tau_y, tau_z] into 4 motor thrusts [u1, u2, u3, u4].
    #   F_z:   Total vertical collective thrust (N)
    #   tau_x: Roll torque around body X-axis (N*m) - tilts left/right
    #   tau_y: Pitch torque around body Y-axis (N*m) - tilts nose up/down
    #   tau_z: Yaw torque around body Z-axis (N*m) - rotates heading
    #
    # Derived from arm geometry (dx=0.14m, dy=0.18m) and torque-to-thrust ratio (c_tau=0.0201).
    b_inv: np.ndarray = field(default_factory=lambda: np.array([
        [0.25, -1.3889,  1.7857, -12.4378],  # Motor 1 (rear-left)
        [0.25,  1.3889,  1.7857,  12.4378],  # Motor 2 (rear-right)
        [0.25,  1.3889, -1.7857, -12.4378],  # Motor 3 (front-right)
        [0.25, -1.3889, -1.7857,  12.4378]   # Motor 4 (front-left)
    ]))


# ==============================================================================
# SYSTEM 1 (REFLEX PID) CONTROLLER GAINS
# ==============================================================================
@dataclass
class PIDConfig:
    """Proportional-Derivative (PID) gains for System 1 reflex control.
    
    System 1 runs at high frequency (500Hz) to keep the drone balanced.
    
    - Kp (Proportional gain): 'How hard to push towards target based on current error'
    - Kd (Derivative gain):   'Damping force to stop oscillations and prevent overshoot'
    """
    # 1. Altitude Control (Vertical Z axis)
    # Restores drone back to TARGET_Z (1.0m)
    kp_z: float = 25.0
    kd_z: float = 10.0
    
    # 2. Attitude Control (Roll & Pitch tilt angles)
    # Keeps drone level so it doesn't flip over
    kp_att: float = 2.0
    kd_att: float = 0.55
    
    # 3. Heading / Yaw Control (Rotation around vertical axis)
    # Keeps drone facing forward (yaw = 0)
    kp_yaw: float = 0.5
    kd_yaw: float = 0.15
    
    # 4. Horizontal Position Hold (X and Y coordinates)
    # Generates a slight tilt angle to push drone back towards (x=0, y=0)
    kp_xy: float = 0.15
    kd_xy: float = 0.35
    
    # Maximum allowable tilt angle (in radians) generated by position hold
    # 0.15 radians is ~8.6 degrees, keeping drone safe from flipping during reflex
    max_tilt_rad: float = 0.15


# ==============================================================================
# SYSTEM 1 (L1 ADAPTIVE + GEOMETRIC) CONTROLLER CONFIGURATION
# ==============================================================================
@dataclass
class L1Config:
    """Parameters for SE(3) Geometric Controller and L1 Adaptive Augmentation.

    Based on 'L1Quad: L1 Adaptive Augmentation of Geometric Control for Agile Quadrotors
    With Performance Guarantees' (IEEE Transactions on Control Systems Technology, 2025).
    """
    # Geometric Baseline Controller gains
    # k_p: Position gains [x, y, z]
    pos_gains: np.ndarray = field(default_factory=lambda: np.array([3.0, 3.0, 15.0], dtype=np.float32))
    # k_v: Velocity gains [x, y, z]
    vel_gains: np.ndarray = field(default_factory=lambda: np.array([2.5, 2.5, 8.0], dtype=np.float32))
    # k_R: Attitude gains [roll, pitch, yaw]
    att_gains: np.ndarray = field(default_factory=lambda: np.array([3.5, 3.5, 1.2], dtype=np.float32))
    # k_W: Angular velocity gains [roll_rate, pitch_rate, yaw_rate]
    ang_gains: np.ndarray = field(default_factory=lambda: np.array([0.7, 0.7, 0.25], dtype=np.float32))

    # L1 Adaptive Augmentation parameters
    # As_v: Velocity adaptation Hurwitz gain (strictly negative)
    as_v: float = -5.0
    # As_W: Angular velocity adaptation Hurwitz gain (strictly negative)
    as_w: float = -20.0
    # Cutoff frequencies for low-pass filters (Hz)
    lpf1_cutoff_freq_force: float = 10.0
    lpf1_cutoff_freq_moment: float = 10.0
    lpf2_cutoff_freq_moment: float = 5.0
    # Scaling factor for horizontal velocity estimation error
    vtilde_xy_scale: float = 1.0

    # Fast Trigger limits (detecting when to alert System 2)
    pos_error_threshold: float = 0.30        # meters
    tilt_error_threshold_deg: float = 25.0   # degrees
    gyro_rms_threshold: float = 3.5          # rad/s
    force_disturbance_threshold: float = 3.0 # Newtons



# ==============================================================================
# CHAOS INJECTION & FAILURE MODE SETTINGS
# ==============================================================================
@dataclass
class ChaosConfig:
    """Configuration for simulated hardware failures and disturbances."""
    # Chaos 1: Motor 1 Thrust Loss (Chipped propeller or ESC overheating)
    # 0.40 means motor produces only 40% of commanded thrust (60% power cut)
    motor_failure_multiplier: float = 0.40
    
    # Chaos 2: Physical Swinging Payload
    # Mass of payload bob is 0.35 kg (26% of drone weight) attached on a 0.25m tether
    payload_kick_angle_rad: float = 0.30   # Initial kick angle (~17 degrees)
    payload_kick_velocity: float = 1.5     # Initial kick angular speed (rad/s)
    
    # Chaos 3: Sensor Noise (Vibration / noisy IMU)
    # Adds zero-mean Gaussian noise to gyroscope angular velocity readings
    sensor_noise_std: float = 3.5  # rad/s standard deviation
    
    # Chaos 4: External Wind Gust
    # Lateral push applied directly to the drone body
    wind_gust_force_newtons: float = 5.0   # 5.0 N lateral force
    wind_gust_duration_seconds: float = 0.80  # Duration of the gust


# ==============================================================================
# SIMULATION & VIEWER SETTINGS
# ==============================================================================
@dataclass
class SimConfig:
    """MuJoCo physics loop and rendering parameters."""
    physics_timestep: float = 0.002        # 500 Hz physics update rate (2 ms)
    render_fps: float = 60.0               # 60 FPS viewer sync rate
    telemetry_print_interval: float = 1.2  # Seconds between terminal telemetry logs
    
    # Auto-tracking camera configuration
    cam_distance: float = 2.2    # Distance in meters from drone
    cam_elevation: float = -18.0 # Pitch angle looking slightly down
    cam_azimuth: float = 45.0    # 45 degree angle for clear perspective
